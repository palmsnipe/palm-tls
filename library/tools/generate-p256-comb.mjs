import fs from "node:fs";

const outputPath = process.argv[2];
const format = process.argv[3] ?? "arm";
if (!outputPath || !["arm", "m68k"].includes(format))
    throw new Error("usage: generate-p256-comb.mjs OUTPUT [arm|m68k]");

const p = (1n << 256n) - (1n << 224n) + (1n << 192n) +
    (1n << 96n) - 1n;
const generator = {
    x: BigInt("0x6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296"),
    y: BigInt("0x4fe342e2fe1a7f9b8ee7eb4a7c0f9e162bce33576b315ececbb6406837bf51f5")
};
const montgomeryR = (1n << 256n) % p;

function mod(value) {
    value %= p;
    return value < 0n ? value + p : value;
}

function power(base, exponent) {
    let result = 1n;
    while (exponent !== 0n) {
        if ((exponent & 1n) !== 0n) result = mod(result * base);
        base = mod(base * base);
        exponent >>= 1n;
    }
    return result;
}

function inverse(value) {
    return power(value, p - 2n);
}

function add(left, right) {
    if (left === null) return right;
    if (right === null) return left;
    if (left.x === right.x) {
        if (left.y !== right.y || left.y === 0n) return null;
        const slope = mod((3n * left.x * left.x - 3n) *
            inverse(2n * left.y));
        const x = mod(slope * slope - 2n * left.x);
        return {x, y: mod(slope * (left.x - x) - left.y)};
    }
    const slope = mod((right.y - left.y) * inverse(right.x - left.x));
    const x = mod(slope * slope - left.x - right.x);
    return {x, y: mod(slope * (left.x - x) - left.y)};
}

function limbs(value) {
    const bits = format === "m68k" ? 16 : 32;
    const mask = (1n << BigInt(bits)) - 1n;
    return Array.from({length: 256 / bits}, (_, index) => {
        const word = (value >> BigInt(index * bits)) & mask;
        return `0x${word.toString(16).padStart(bits / 4, "0")}U`;
    }).join(",");
}

const width = format === "arm" ? 5 : 6;
const tables = format === "arm" ? 3 : 1;
const windows = Math.ceil(256 / (width * tables));
const digits = (1 << width) - 1;

function combTable(tableIndex) {
    let tooth = generator;
    for (let bit = 0; bit < tableIndex * windows; bit++) tooth = add(tooth, tooth);
    const basis = [tooth];
    for (let index = 1; index < width; index++) {
        for (let bit = 0; bit < tables * windows; bit++) tooth = add(tooth, tooth);
        basis.push(tooth);
    }
    const rows = [];
    for (let digit = 1; digit <= digits; digit++) {
        let point = null;
        for (let bit = 0; bit < width; bit++)
            if ((digit & (1 << bit)) !== 0) point = add(point, basis[bit]);
        rows.push(` {{{${limbs(mod(point.x * montgomeryR))}}},{{${limbs(mod(point.y * montgomeryR))}}}}`);
    }
    return rows.join(",\n");
}

// Public width-7 wNAF digits select G, 3G, ... 63G. Unlike the private-scalar
// comb table above, this small affine table can be indexed directly.
const oddTable = [];
const twiceGenerator = add(generator, generator);
let oddPoint = generator;
for (let index = 0; index < 32; index++) {
    oddTable.push(` {{{${limbs(mod(oddPoint.x * montgomeryR))}}},{{${limbs(mod(oddPoint.y * montgomeryR))}}}}`);
    oddPoint = add(oddPoint, twiceGenerator);
}

// Raw coordinates for recognizing the generator at the scalar-multiply ABI.
function bigEndianWords(value) {
    return Array.from({length: 8}, (_, index) => {
        const word = (value >> BigInt(32 * (7 - index))) & 0xffffffffn;
        return `0x${word.toString(16).padStart(8, "0")}U`;
    }).join(",");
}

const source = [
    "/* Generated by tools/generate-p256-comb.mjs. */",
    `#define P256_COMB_WIDTH ${width}U`,
    `#define P256_COMB_WINDOWS ${windows}U`,
    `#define P256_COMB_DIGITS ${digits}U`,
    ...(format === "arm" ? [
        "static const u32 kGeneratorWords[16] = {",
        ` ${bigEndianWords(generator.x)},`,
        ` ${bigEndianWords(generator.y)}`,
        "};",
    ] : [
        `static const Fe256 kMontgomerySquare = {{${limbs(mod(montgomeryR ** 2n))}}};`,
    ]),
    ...(format === "arm" ? [
        `#define P256_COMB_TABLES ${tables}U`,
        "static const Affine256 kGeneratorComb[P256_COMB_TABLES][P256_COMB_DIGITS] = {",
        Array.from({length: tables}, (_, index) => `{\n${combTable(index)}\n}`).join(",\n"),
    ] : [
        "static const Affine256 kGeneratorComb[P256_COMB_DIGITS] = {",
        combTable(0),
    ]),
    "};",
    "/* Public double-scalar width-7 wNAF table in Montgomery form. */",
    "static const Affine256 kGeneratorOdd[32] = {",
    oddTable.join(",\n"),
    "};",
    ""
].join("\n");
fs.writeFileSync(outputPath, source);
