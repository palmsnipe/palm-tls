import fs from "node:fs";

const outputPath = process.argv[2];
if (!outputPath) throw new Error("usage: generate-p256-comb.mjs OUTPUT");

const p = (1n << 256n) - (1n << 224n) + (1n << 192n) +
    (1n << 96n) - 1n;
const generator = {
    x: BigInt("0x6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296"),
    y: BigInt("0x4fe342e2fe1a7f9b8ee7eb4a7c0f9e162bce33576b315ececbb6406837bf51f5")
};
const montgomeryR = (1n << 256n) % p;

function mod(value) {
    value %= p;
    return value < 0n ? value + p : value;
}

function power(base, exponent) {
    let result = 1n;
    while (exponent !== 0n) {
        if ((exponent & 1n) !== 0n) result = mod(result * base);
        base = mod(base * base);
        exponent >>= 1n;
    }
    return result;
}

function inverse(value) {
    return power(value, p - 2n);
}

function add(left, right) {
    if (left === null) return right;
    if (right === null) return left;
    if (left.x === right.x) {
        if (left.y !== right.y || left.y === 0n) return null;
        const slope = mod((3n * left.x * left.x - 3n) *
            inverse(2n * left.y));
        const x = mod(slope * slope - 2n * left.x);
        return {x, y: mod(slope * (left.x - x) - left.y)};
    }
    const slope = mod((right.y - left.y) * inverse(right.x - left.x));
    const x = mod(slope * slope - left.x - right.x);
    return {x, y: mod(slope * (left.x - x) - left.y)};
}

function limbs(value) {
    value = mod(value * montgomeryR);
    const result = [];
    for (let index = 0n; index < 8n; index++) {
        const limb = Number((value >> (index * 32n)) & 0xffffffffn);
        result.push(`0x${limb.toString(16).padStart(8, "0")}U`);
    }
    return result.join(",");
}

const basis = [generator];
for (let index = 1; index < 8; index++) {
    let point = basis[index - 1];
    for (let doubling = 0; doubling < 32; doubling++)
        point = add(point, point);
    basis.push(point);
}

const table = [];
for (let digit = 1; digit < 256; digit++) {
    let point = null;
    for (let bit = 0; bit < 8; bit++)
        if ((digit & (1 << bit)) !== 0) point = add(point, basis[bit]);
    table.push(` {{{${limbs(point.x)}}},{{${limbs(point.y)}}}}`);
}

const source = [
    "/* Generated by tools/generate-p256-comb.mjs. */",
    "static const Affine256 kGeneratorComb[255] = {",
    table.join(",\n"),
    "};",
    ""
].join("\n");
fs.writeFileSync(outputPath, source);
