// Independent AES-GCM oracle, using Node's OpenSSL implementation.
import { createCipheriv } from 'node:crypto';
import { writeFileSync } from 'node:fs';

function encrypt(data) {
    const cipher = createCipheriv('aes-128-gcm', Buffer.alloc(16), Buffer.alloc(12));
    cipher.setAAD(Buffer.alloc(13));
    const bytes = Buffer.concat([cipher.update(data), cipher.final()]);
    return { bytes, tag: cipher.getAuthTag() };
}
function checksum(bytes) {
    let value = 2166136261;
    for (const byte of bytes) value = Math.imul(value ^ byte, 16777619) >>> 0;
    return value;
}
const rows = [16, 512, 4096, 16384].map(size => {
    const { bytes, tag } = encrypt(Buffer.alloc(size));
    // Encrypting the CTR keystream yields an all-zero ciphertext. Its tag is
    // the oracle for decrypting all-zero input in the benchmark.
    const decryptTag = encrypt(bytes).tag;
    const array = data => `{${[...data].join(',')}}`;
    return `{${checksum(bytes.subarray(-Math.min(size, 512)))}UL,` +
           `${array(tag)},${array(decryptTag)}}`;
});
// Independent BigInt oracle for the raw Montgomery-residue chains. Keep this
// count synchronized with BENCH_FIELD_ITERATIONS in bench.h.
const p = (1n << 256n) - (1n << 224n) + (1n << 192n) + (1n << 96n) - 1n;
const r = 1n << 256n;
function power(base, exponent) {
    let value = 1n;
    while (exponent) {
        if (exponent & 1n) value = value * base % p;
        base = base * base % p;
        exponent >>= 1n;
    }
    return value;
}
const inverseR = power(r % p, p - 2n);
const a = 0xc9afa9d845ba75166b5c215767b1d6934e50c3db36e89b127b8a622b120f6721n;
const b = 0xeeabcdef0123456789abcdef0123456789abcdef0123456789abcdef01234567n;
const fieldRows = [0, 1, 2].map(operation => {
    let value = a;
    for (let index = 0; index < 128; index++)
        value = (operation === 0 ? value * b * inverseR :
                 operation === 1 ? value * value * inverseR :
                 value * inverseR + b) % p;
    return `"${value.toString(16).padStart(64, '0')}"`;
});
writeFileSync(process.argv[2],
    '/* Generated by bench/generate-vectors.mjs; do not edit. */\n' +
    'static const struct { BenchWord tail; unsigned char encrypt[16], decrypt[16]; }\n' +
    `kGcmVectors[] = {${rows.join(',\n')}};\n` +
    `static const char kFieldVectors[3][65] = {${fieldRows.join(',\n')}};\n`);
